from __future__ import annotations
from typing import Any, Protocol

class DeviceClient(Protocol):

    async def command(self, command: str, params: dict[str, Any] | None=None, *, timeout: float=60.0) -> dict[str, Any]:
        ...

    async def action(self, action: str, arguments: dict[str, Any] | None=None, *, timeout: float=10.0) -> dict[str, Any]:
        ...

    async def status(self) -> dict[str, Any]:
        ...

    async def screen_state(self) -> dict[str, Any]:
        ...

    async def top_activity(self) -> dict[str, Any]:
        ...

    async def page_elements(self, light: bool=False) -> dict[str, Any]:
        ...

    async def page_icons(self, desktop_package: str) -> dict[str, Any]:
        ...

    async def screenshot(self, name: str, *, scale_factor: float=1.0) -> dict[str, Any]:
        ...

    async def click(self, x: float, y: float) -> dict[str, Any]:
        ...

    async def double_click(self, x: float, y: float) -> dict[str, Any]:
        ...

    async def long_click(self, x: float, y: float) -> dict[str, Any]:
        ...

    async def input_text(self, text: str) -> dict[str, Any]:
        ...

    async def swipe(self, *, direction: str | None=None, start: list[float] | tuple[float, float] | None=None, end: list[float] | tuple[float, float] | None=None, times: int=1, interval: float=1.0) -> dict[str, Any]:
        ...

    async def drag(self, start: list[float] | tuple[float, float], end: list[float] | tuple[float, float], *, duration: float=1.0) -> dict[str, Any]:
        ...

    async def back(self) -> dict[str, Any]:
        ...

    async def home(self) -> dict[str, Any]:
        ...

    async def open_multitask(self) -> dict[str, Any]:
        ...

    async def open_control(self) -> dict[str, Any]:
        ...

    async def open_notification(self) -> dict[str, Any]:
        ...

    async def start_app(self, app_name: str) -> dict[str, Any]:
        ...

    async def stop_app(self) -> dict[str, Any]:
        ...

    async def script_write(self, script_name: str, content: str, *, timeout: float=30.0) -> dict[str, Any]:
        ...
